export { DICT };
// ---------------------------------------------------------------------------
// Language state, lookup, number formatting, and a `data-i18n` markup pass.
// ---------------------------------------------------------------------------

const SAVE_KEY = 'fishing-adventure-save-v1';

function detectLang(): Lang {
  try {
    const saved = JSON.parse(localStorage.getItem(SAVE_KEY) || '{}').lang as Lang | undefined;
    if (saved === 'de' || saved === 'en') return saved;
  } catch { /* ignore — storage may be unavailable (private mode, SSR, dev sheet) */ }
  const nav = (typeof navigator !== 'undefined' ? navigator.language : 'de') || 'de';
  return nav.toLowerCase().startsWith('de') ? 'de' : 'en';
}

let currentLang: Lang = detectLang();
const listeners = new Set<(lang: Lang) => void>();

export function getLang(): Lang { return currentLang; }

export function setLang(lang: Lang): void {
  if (lang === currentLang) return;
  currentLang = lang;
  try {
    const raw = JSON.parse(localStorage.getItem(SAVE_KEY) || '{}');
    raw.lang = lang;
    localStorage.setItem(SAVE_KEY, JSON.stringify(raw));
  } catch { /* ignore */ }
  for (const fn of listeners) fn(lang);
}

/** Called after every `setLang` — e.g. to re-run `applyI18n` over live markup. */
export function onLangChange(fn: (lang: Lang) => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/**
 * Translate one dictionary key (the German source string, verbatim).
 * German is the source language, so `t()` is a no-op identity in `de`.
 * Optional `vars` does simple `{name}` substitution AFTER lookup, so a
 * dictionary entry can carry placeholders (e.g. `t("Fange {n} Fische")`
 * style callers build the key with the count baked in already, matching
 * how the old dictionary itself has one entry per concrete phrase rather
 * than an ICU message format — see spec §6.5).
 */
export function t(key: string, vars?: Record<string, string | number>): string {
  let s = currentLang === 'de' ? key : (Object.prototype.hasOwnProperty.call(DICT, key) ? DICT[key] : key);
  if (vars) {
    for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  }
  return s;
}

/** German uses a comma decimal separator; English keeps the period (spec §6.3). */
export function num(n: number, dec?: number): string {
  const s = dec != null ? n.toFixed(dec) : String(n);
  return currentLang === 'de' ? s.replace('.', ',') : s;
}

/**
 * Walks `root` for `data-i18n="<key>"` and sets `textContent` to `t(key)`,
 * and `data-i18n-attr="attrName:<key>"` to translate an attribute (e.g.
 * `aria-label`/`title`) instead of the node's text — so markup can be
 * authored once and re-translated in place on every language switch.
 */
export function applyI18n(root: ParentNode): void {
  const nodes = root.querySelectorAll<HTMLElement>('[data-i18n]');
  for (const el of nodes) {
    const key = el.dataset.i18n;
    if (key) el.textContent = t(key);
  }
  const attrNodes = root.querySelectorAll<HTMLElement>('[data-i18n-attr]');
  for (const el of attrNodes) {
    const spec = el.dataset.i18nAttr;
    if (!spec) continue;
    const idx = spec.indexOf(':');
    if (idx < 0) continue;
    const attr = spec.slice(0, idx), key = spec.slice(idx + 1);
    el.setAttribute(attr, t(key));
  }
}
