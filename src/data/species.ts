/**
 * Species that can spawn at a given location, filtered by day/night — mirrors the old
 * `pickSpecies()` pool build (`fish.js:88`): `SPECIES.filter(s => s.loc.includes(here) && (!s.night || night) && !s.boss)`.
 * Bosses are excluded here too — they're picked separately once a location's dex is complete
 * (see `bossFor`/`bossUnlocked` in the old `shop.js`), which is game-logic, not species data.
 */
export function speciesForLocation(loc: string, night: boolean): Species[] {
  return SPECIES.filter(s => s.locations.includes(loc) && (!s.nightOnly || night) && !s.boss);
}
