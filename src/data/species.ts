/** Exactly the old game's rarity ids (`fish.js` RARITY keys). */
export type Rarity = "common" | "uncommon" | "rare" | "epic" | "legendary";

/**
 * `pattern` is the old `sp.pattern` field verbatim — it does double duty in the old game:
 * for generic fish it is a surface-decoration key (stripes/spots/scales/...), for everything in
 * `CREATURE_DRAW` (creatures.js) it is a full alternate body-type key, and for boot/bottle/chest
 * it short-circuits to a unique junk-item drawer. `bodyType` is a small derived convenience (NOT
 * present in the old data) that pre-classifies which of those three drawing paths `pattern`
 * selects, so `src/bake/fishArt.ts` doesn't need to re-derive it from a hardcoded pattern list.
 */
export type BodyType = "fish" | "creature" | "boot" | "bottle" | "chest";

export interface SpeciesColors {
  /** `sp.color` — main body color (hex, or rgba() for the two jellyfish). */
  body: string;
  /** `sp.belly` — belly/underside color. */
  belly: string;
  /** `sp.fin` — fin/accent color. */
  fin: string;
}

export interface Species {
  id: string;
  nameDe: string;
  nameEn: string;
  rarity: Rarity;
  /** location ids this species can spawn at, e.g. ["see", "boot"]. */
  locations: readonly string[];
  /** depth band [d0, d1], 0 = surface, 1 = bottom (`sp.depth`). */
  depth: readonly [number, number];
  /** body length multiplier (`sp.len`). */
  len: number;
  /** body height multiplier (`sp.h`). */
  h: number;
  /** catch weight range in kg (`sp.kg`). */
  weight: readonly [number, number];
  /** swim speed multiplier (`sp.speed`). */
  speed: number;
  /** reel minigame difficulty (`sp.fight`). */
  fight: number;
  /** base coin payout, pre-`COIN_SCALE` (`sp.value`). */
  value: number;
  colors: SpeciesColors;
  /** surface-pattern / body-type key, verbatim `sp.pattern` — see `BodyType` doc above. */
  pattern: string;
  /** derived from `pattern`, see `BodyType` doc above. */
  bodyType: BodyType;
  /** `sp.night` — only spawns while it's night. */
  nightOnly?: boolean;
  /** `sp.boss` — location boss, only spawns once its location's non-boss dex is complete. */
  boss?: boolean;
  /** `sp.junk` — bycatch (boot/bottle/chest/seaweed/starfish/frozen fish/penguin), skips the
   *  perfect-catch/streak coin multiplier at catch time. */
  bycatch?: boolean;
  /** `sp.glow` — explicit glow flag, ON TOP of the glow/moon/lure patterns which also glow
   *  (see old `isGlowing(sp)`, fish.js:67). */
  glow?: boolean;
  triviaDe: string;
  triviaEn: string;
}

